/**
 * Compiles contracts/verify/VerifySim.sol into lib/verify/sim-artifact.ts.
 *
 * The simulator is never deployed. Verify injects its runtime bytecode into an
 * eth_call with a state override, so the app needs the bytecode as a constant,
 * not an address. Rerun this after any change to the contract:
 *
 *   npx -y -p solc@0.8.26 node scripts/build-verify-sim.mjs
 *
 * The compiler version and settings are pinned so the committed artifact can be
 * reproduced byte for byte.
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const solc = require("solc");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "contracts/verify/VerifySim.sol"), "utf8");

const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources: { "VerifySim.sol": { content: source } },
      settings: {
        optimizer: { enabled: true, runs: 200 },
        viaIR: true,
        evmVersion: "cancun",
        outputSelection: { "*": { VerifySim: ["abi", "evm.deployedBytecode.object"] } },
      },
    }),
  ),
);

const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

const contract = output.contracts["VerifySim.sol"].VerifySim;
const runtime = `0x${contract.evm.deployedBytecode.object}`;

writeFileSync(
  join(root, "lib/verify/sim-artifact.ts"),
  `/**
 * GENERATED by scripts/build-verify-sim.mjs from contracts/verify/VerifySim.sol.
 * Do not edit by hand. Compiler: solc ${solc.version()}, optimizer 200 runs, via IR.
 */

export const VERIFY_SIM_ABI = ${JSON.stringify(contract.abi, null, 2)} as const;

export const VERIFY_SIM_RUNTIME = "${runtime}" as const;
`,
);

console.log(`lib/verify/sim-artifact.ts written, ${runtime.length / 2 - 1} bytes of runtime`);
